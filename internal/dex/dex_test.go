func testConfig() *config.Config {
	return &config.Config{
		Version:    config.ConfigVersion,
		SetupState: config.SetupStateReady,
		School: config.School{
			Name:         "Gymnasium Phoenix",
			Slug:         "phoenix",
			ServerDomain: "192.168.1.10",
		},
		Public: config.Public{
			Transport:  config.TransportDirect,
			BaseDomain: "ls.gym-phoenix.de",
		},
	}
}

func TestGenerateConfigBasic(t *testing.T) {
	cfg := testConfig()
	clients := []Client{
		{
			ID:           "langflow",
			Secret:       "abc123",
			Name:         "Langflow",
			RedirectURIs: []string{"https://langflow.ls.gym-phoenix.de/oauth/callback"},
		},
	}

	data, err := GenerateConfig(cfg, clients)
	if err != nil {
		t.Fatalf("GenerateConfig: %v", err)
	}
	content := string(data)

	// Banner.
	if !strings.HasPrefix(content, "# Generated by stackctl") {
		t.Error("banner missing")
	}

	// Parse to verify structure.
	var doc map[string]any
	if err := yaml.Unmarshal(data, &doc); err != nil {
		t.Fatalf("invalid YAML: %v\n%s", err, content)
	}

	// Issuer.
	if doc["issuer"] != "https://auth.ls.gym-phoenix.de" {
		t.Errorf("issuer = %v", doc["issuer"])
	}

	// Storage.
	storage := doc["storage"].(map[string]any)
	if storage["type"] != "sqlite3" {
		t.Errorf("storage type = %v", storage["type"])
	}

	// Kein Anmeldedienst angebunden: Dex startet ohne jeden Connector nicht,
	// die Passwort-Datenbank zaehlt als einer — auch leer. Ein
	// Upstream-Connector darf es nicht geben, schon gar nicht einer auf einen
	// Dritten.
	if doc["enablePasswordDB"] != true {
		t.Errorf("enablePasswordDB = %v, want true — sonst startet Dex nicht", doc["enablePasswordDB"])
	}
	if _, ok := doc["connectors"]; ok {
		t.Errorf("connectors = %v, want none", doc["connectors"])
	}
	if _, ok := doc["staticPasswords"]; ok {
		t.Error("ohne Testkonten darf es keine Passwort-Eintraege geben")
	}

	// oauth2 settings.
	oauth2 := doc["oauth2"].(map[string]any)
	if oauth2["skipApprovalScreen"] != true {
		t.Errorf("skipApprovalScreen = %v", oauth2["skipApprovalScreen"])
	}

	// Static clients.
	staticClients := doc["staticClients"].([]any)
	if len(staticClients) != 1 {
		t.Fatalf("staticClients count = %d", len(staticClients))
	}
	sc := staticClients[0].(map[string]any)
	if sc["id"] != "langflow" {
		t.Errorf("client id = %v", sc["id"])
	}
}

func TestGenerateConfigNoClients(t *testing.T) {
	cfg := testConfig()
	data, err := GenerateConfig(cfg, nil)
	if err != nil {
		t.Fatalf("GenerateConfig: %v", err)
	}
	var doc map[string]any
	yaml.Unmarshal(data, &doc)
	if _, ok := doc["staticClients"]; ok {
		t.Error("empty clients should omit staticClients block")
	}
}

func TestAddClientIdempotent(t *testing.T) {
	existing := []Client{
		{ID: "langflow", Secret: "old", Name: "Langflow", RedirectURIs: []string{"https://old"}},
	}
	updated := Client{ID: "langflow", Secret: "new", Name: "Langflow v2", RedirectURIs: []string{"https://new"}}

	// We can't call AddClient because it calls SaveConfig (needs docker).
	// Test the replacement logic manually.
	result := make([]Client, 0, len(existing)+1)
	replaced := false
	for _, c := range existing {
		if c.ID == updated.ID {
			result = append(result, updated)
			replaced = true
		} else {
			result = append(result, c)
		}
	}
	if !replaced {
		result = append(result, updated)
	}

	if len(result) != 1 {
		t.Errorf("count = %d, want 1", len(result))
	}
	if result[0].Secret != "new" {
		t.Errorf("secret = %q, want new", result[0].Secret)
	}
}

func TestBuildRedirectURI(t *testing.T) {
	cfg := testConfig()

	// Public URL.
	got := BuildRedirectURI(cfg, "langflow", "/oauth/callback", 8320, true)
	want := "https://langflow.ls.gym-phoenix.de/oauth/callback"
	if got != want {
		t.Errorf("BuildRedirectURI public = %q, want %q", got, want)
	}

	// Local URL.
	got = BuildRedirectURI(cfg, "langflow", "/oauth/callback", 8320, false)
	want = "http://192.168.1.10:8320/oauth/callback"
	if got != want {
		t.Errorf("BuildRedirectURI local = %q, want %q", got, want)
	}
}

// A school on its own domain must get its apps and its issuer under that
// domain — this is the regression the pre-v3 string concatenation could not
// express at all.
func TestBuildRedirectURICustomDomain(t *testing.T) {
	cfg := testConfig()
	cfg.Public.BaseDomain = "ls.gym-phoenix.de"

	got := BuildRedirectURI(cfg, "pylearn", "/auth/callback", 8330, true)
	want := "https://pylearn.ls.gym-phoenix.de/auth/callback"
	if got != want {
		t.Errorf("BuildRedirectURI = %q, want %q", got, want)
	}
}

// Testkonten landen als Passwort-Eintraege in Dex, in der Form des
// Claim-Kontrakts: die zufaellige ID wird zum Subjekt, die Rolle zum einzigen
// groups-Wert. Dex 2.45 liest name, preferredUsername und groups.
func TestGenerateConfigTestAccounts(t *testing.T) {
	cfg := testConfig()
	cfg.Auth.TestAccounts = []config.TestAccount{{
		ID:           "0123abcd",
		Name:         "Frau Mueller",
		Role:         "lehrkraft",
		Login:        "mueller@ls.gym-phoenix.de",
		PasswordHash: "$2a$10$abcdefghijklmnopqrstuuJ8lC0XxS0bU0R9J2yXz1Hq5mW0lY8xK",
	}}

	data, err := GenerateConfig(cfg, nil)
	if err != nil {
		t.Fatalf("GenerateConfig: %v", err)
	}
	var doc struct {
		EnablePasswordDB bool `yaml:"enablePasswordDB"`
		StaticPasswords  []struct {
			Email             string   `yaml:"email"`
			Hash              string   `yaml:"hash"`
			Name              string   `yaml:"name"`
			PreferredUsername string   `yaml:"preferredUsername"`
			UserID            string   `yaml:"userID"`
			Groups            []string `yaml:"groups"`
		} `yaml:"staticPasswords"`
	}
	if err := yaml.Unmarshal(data, &doc); err != nil {
		t.Fatalf("invalid YAML: %v", err)
	}
	if !doc.EnablePasswordDB {
		t.Error("enablePasswordDB must be on for static passwords")
	}
	if len(doc.StaticPasswords) != 1 {
		t.Fatalf("staticPasswords = %d entries, want 1", len(doc.StaticPasswords))
	}
	p := doc.StaticPasswords[0]
	want := cfg.Auth.TestAccounts[0]
	if p.Email != want.Login || p.Hash != want.PasswordHash || p.UserID != want.ID || p.Name != want.Name {
		t.Errorf("entry = %+v, want login/hash/id/name from %+v", p, want)
	}
	if p.PreferredUsername != "mueller" {
		t.Errorf("preferredUsername = %q, want the part before the @", p.PreferredUsername)
	}
	if len(p.Groups) != 1 || p.Groups[0] != "lehrkraft" {
		t.Errorf("groups = %v, want [lehrkraft]", p.Groups)
	}
}
